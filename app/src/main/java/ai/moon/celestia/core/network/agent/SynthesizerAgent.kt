package ai.moon.celestia.core.network.agent

import ai.moon.celestia.core.network.DeepResearchReport
import ai.moon.celestia.core.network.ExtractedSource
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

class SynthesizerAgent private constructor() {
    companion object {
        @Volatile
        private var INSTANCE: SynthesizerAgent? = null

        fun getInstance(): SynthesizerAgent {
            return INSTANCE ?: synchronized(this) {
                INSTANCE ?: SynthesizerAgent().also { INSTANCE = it }
            }
        }
    }

    suspend fun synthesizeReport(
        userQuery: String,
        sources: List<ExtractedSource>,
        startTimeMs: Long
    ): DeepResearchReport = withContext(Dispatchers.Default) {
        val executionTime = System.currentTimeMillis() - startTimeMs
        if (sources.isEmpty()) {
            return@withContext DeepResearchReport(
                finalReportText = "No verified web sources could be extracted for query: '$userQuery'.",
                sources = emptyList(),
                totalSourcesScraped = 0,
                executionTimeMs = executionTime
            )
        }

        val sb = StringBuilder()
        sb.append("### Comprehensive Research Report: **$userQuery**\n\n")
        sb.append("Synthesized from ${sources.size} verified web sources:\n\n")

        sources.forEachIndexed { index, source ->
            sb.append("${index + 1}. **[${source.title}](${source.url})**\n")
            sb.append("   *Objective:* ${source.subQueryObjective}\n")
            val summary = if (source.summaryText.isNotBlank()) source.summaryText else source.markdownContent.take(200)
            sb.append("   *Findings:* $summary...\n\n")
        }

        sb.append("---\n*Generated by Celestia Deep Research AI Agent in ${executionTime}ms.*")

        DeepResearchReport(
            finalReportText = sb.toString(),
            sources = sources,
            totalSourcesScraped = sources.size,
            executionTimeMs = executionTime
        )
    }
}
